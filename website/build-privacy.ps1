# Regenerates website/privacy.html from the in-app policy (app/src/main/assets/legal/privacy-policy.txt),
# so the hosted policy and the one in the app are always word-for-word identical.
# Run from the repository root:  powershell -ExecutionPolicy Bypass -File website\build-privacy.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$src = [IO.File]::ReadAllLines((Join-Path $root 'app\src\main\assets\legal\privacy-policy.txt'), [Text.Encoding]::UTF8)
function Esc([string]$s) { [System.Net.WebUtility]::HtmlEncode($s) }

$title = $src[0]; $effective = $src[1]
$body = New-Object System.Text.StringBuilder
$inList = $false
for ($i = 2; $i -lt $src.Length; $i++) {
    $line = $src[$i].Trim()
    if ($line -eq '') { if ($inList) { [void]$body.AppendLine('      </ul>'); $inList = $false }; continue }
    $next = if ($i + 1 -lt $src.Length) { $src[$i + 1].Trim() } else { '' }
    $prev = if ($i -gt 0) { $src[$i - 1].Trim() } else { '' }
    if ($line.StartsWith('- ')) {
        if (-not $inList) { [void]$body.AppendLine('      <ul>'); $inList = $true }
        [void]$body.AppendLine("        <li>$(Esc $line.Substring(2))</li>")
    } elseif ($prev -eq '' -and $next -ne '' -and $line.Length -lt 45 -and -not $line.EndsWith('.')) {
        [void]$body.AppendLine("      <h2>$(Esc $line)</h2>")
    } else {
        [void]$body.AppendLine("      <p>$(Esc $line)</p>")
    }
}
if ($inList) { [void]$body.AppendLine('      </ul>') }

$html = @"
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Privacy Policy &middot; PDF Editor: Perpetual Apps</title>
<meta name="description" content="Privacy policy for PDF Editor: Perpetual Apps. Nothing is collected, and the app has no internet permission.">
<link rel="canonical" href="https://pdf.perpetualapps.dev/privacy">
<meta name="theme-color" content="#13463B">
<link rel="icon" href="assets/icon.svg" type="image/svg+xml">
<link rel="stylesheet" href="assets/site.css">
</head>
<body>
<!-- Generated by website/build-privacy.ps1 from app/src/main/assets/legal/privacy-policy.txt. Edit the source, then re-run. -->
<header class="site-header">
  <div class="wrap">
    <a class="brand" href="./" aria-label="PDF Editor: Perpetual Apps, home"><img src="assets/icon.svg" alt="" width="40" height="40"><span><b>PDF Editor</b><small>by Perpetual Apps</small></span></a>
  </div>
</header>
<main class="legal">
  <div class="wrap">
    <a class="back" href="./">&larr; Back to PDF Editor</a>
    <h1>$(Esc $title)</h1>
    <p class="effective">$(Esc $effective)</p>
$($body.ToString().TrimEnd())
  </div>
</main>
<footer class="site-footer">
  <div class="wrap">
    <nav class="footer-links" aria-label="Footer"><a href="./">Home</a><a href="terms">Terms of use</a></nav>
    <p class="fine">&copy; 2026 Perpetual Apps.</p>
  </div>
</footer>
</body>
</html>
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'privacy.html'), $html, (New-Object Text.UTF8Encoding $false))
Write-Output "Wrote website/privacy.html"
